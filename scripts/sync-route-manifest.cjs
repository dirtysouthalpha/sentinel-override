#!/usr/bin/env node
/**
 * One-command heal for route-manifest drift: regenerate the frozen table and
 * commit it if it changed.
 *
 * The whack-a-mole this ends: sibling repos (sentinel-desktop,
 * sentinel-prime-premium, neuralis) take commits from parallel sessions, and
 * the next `npm run check` here fails routes:check through no fault of the
 * change being tested. The fix was always the same two manual steps — this
 * script IS those steps:
 *
 *   npm run routes:sync
 *
 * It never pushes: the commit rides along with whatever the current session
 * pushes next, so a sync can still be reviewed or dropped before publishing.
 * Exit 0 = manifest current (whether or not a commit was made); non-zero =
 * regeneration or git failed.
 */
'use strict';

const { execFileSync } = require('child_process');
const path = require('path');

const REPO = path.join(__dirname, '..');
const MANIFEST = path.join('contract', 'server-routes.json');

function run(cmd, args, opts = {}) {
  return execFileSync(cmd, args, { cwd: REPO, encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'], ...opts });
}

// 1. Regenerate (the generator prints its own summary and fails loudly if no
//    sibling repo is readable).
run(process.execPath, [path.join(__dirname, 'generate-route-manifest.cjs')], { stdio: 'inherit' });

// 2. Commit only if the file actually changed.
const dirty = run('git', ['status', '--porcelain', '--', MANIFEST]).trim();
if (!dirty) {
  console.log('routes:sync — manifest already current, nothing to commit.');
  process.exit(0);
}

run('git', ['add', '--', MANIFEST], { stdio: 'inherit' });
run('git', ['commit', '-m',
  'chore(contract): refresh frozen route manifest (routes:sync)\n\n'
  + 'Sibling server repos changed; re-extracted the committed route tables.\n'
  + 'Generated by scripts/sync-route-manifest.cjs.'],
{ stdio: 'inherit' });
console.log('routes:sync — manifest refreshed and committed (not pushed).');
